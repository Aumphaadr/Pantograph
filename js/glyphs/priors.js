/** Ожидание для знака: null, если знака в замере нет. */
export function nodePrior(ch) {
  const r = PRIORS[ch];
  if (!r) return null;
  return {
    sans: r[0], serif: r[1], contours: r[2],
    corners: { sans: r[3], serif: r[4] },
  };
}

/**
 * Разумный коридор для числа узлов: от трёх четвертей сансерифного до
 * полутора антиквенных. Внутри — обычное дело; снаружи — повод посмотреть.
 */
export function nodeRange(ch) {
  const p = nodePrior(ch);
  if (!p) return null;
  const lo = Math.min(p.sans, p.serif ?? p.sans);
  const hi = Math.max(p.sans, p.serif ?? p.sans);
  return { lo: Math.max(3, Math.round(lo * 0.75)), hi: Math.round(hi * 1.5) };
}

/** 'ok' | 'few' | 'many' | null (знак неизвестен). */
export function judgeNodes(ch, n) {
  const r = nodeRange(ch);
  if (!r) return null;
  if (n < r.lo) return 'few';
  if (n > r.hi) return 'many';
  return 'ok';
}

/** Сумма ожиданий по списку знаков; known — сколько знаков нашлось в таблице. */
export function sheetPrior(chars) {
  let sans = 0;
  let serif = 0;
  let known = 0;
  for (const ch of chars) {
    const p = nodePrior(ch);
    if (!p) continue;
    known += 1;
    sans += p.sans;
    serif += p.serif ?? p.sans;
  }
  return { sans, serif, known };
}

/** Подпись для подсказки: «узлов 14, обычно 12 (сансериф) – 28 (антиква)». */
export function describeNodes(ch, n) {
  const p = nodePrior(ch);
  if (!p) return `узлов ${n}`;
  const usual = p.serif != null && p.serif !== p.sans
    ? `${p.sans} (сансериф) – ${p.serif} (антиква)`
    : `${p.sans}`;
  const verdict = judgeNodes(ch, n);
  const tail = verdict === 'many' ? ' — много' : verdict === 'few' ? ' — мало' : '';
  return `узлов ${n}, обычно ${usual}${tail}`;
}
