// glyphs/priors.js — сколько узлов обычно у буквы.
//
// Замер по двум настоящим шрифтам с известными контурами: Lato (сансериф)
// и FreeSerif (антиква). Их контуры приведены нашим же каноном
// (regularizeShape, допуск 0.5 px при прописных в 68 px), поэтому числа
// сравнимы с тем, что даёт обводка: у «Н» Lato двенадцать узлов — ровно
// двенадцать углов; у антиквы «Н» двадцать восемь — засечки. Кольца «О»
// у Lato не эллиптичны (надутый квадрат), и при этом допуске каждому нужно
// восемь узлов, а не четыре, — таблица честно говорит шестнадцать.
//
// Это ОЖИДАНИЕ, а не норма: буква может законно требовать больше (жирная
// с оптическими компенсациями) или меньше (геометрический гротеск). Нужно
// оно, чтобы заметить перебор и недобор на порядок — не чтобы ужимать.
//
// Строение букв, которое показал замер (см. ARCHITECTURE.md, 4д):
// 1. Прямые буквы — одни углы: Н, П, Т, Ш, Г, Е, Ц. Ни одного гладкого узла.
// 2. Дуги — узлы на экстремумах по x и y, рычаги строго осевые, кусок не
//    длиннее четверти; у надутых («квадратных») колец ещё по узлу между
//    экстремумами — так у «О» Lato восемь узлов на кольцо.
// 3. Стык прямой и дуги — гладкий узел на касательной (сторона «D», «Р»):
//    один узел, а не два.
// 4. Число углов — самое устойчивое в букве: у сансерифа оно и есть почти
//    весь счёт узлов; засечки добавляют по четыре угла на каждую и по узлу
//    на бракет — антиква тяжелее сансерифа в среднем в 1.6 раза.
// 5. Квадратичные TrueType-контуры вдвое-втрое «гуще» кубических: узлы
//    считать после перевода в кубики, иначе ожидание завышено.

