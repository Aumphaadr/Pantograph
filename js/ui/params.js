/**
 * Размер кропа, под который рассчитаны умолчания.
 *
 * Иконка в полсотни пикселей и мастер в тысячу с лишним требуют разных
 * допусков: у мастера все черты во столько же раз крупнее. Единицы остаются
 * абсолютными (пиксели исходника) — они предсказуемы, — но под кроп
 * подгоняются и умолчание, и ПРЕДЕЛЫ ползунка. Иначе ползунок «окно угла»
 * с потолком в четыре пикселя на мастере бесполезен: нужно тридцать.
 */
export const BASE_SIZE = 48;

/**
 * Какие допуски соразмерны фигуре и в какой степени (площадь — во второй).
 *
 * Длины растут медленнее размера (в степени 0.6): у большой картинки край
 * известен точнее в долях размера, и линейный допуск был втрое-вчетверо
 * щедрее, чем нужно, — сверка с настоящими векторными иконками (Solar,
 * tests/iconref.mjs) на 512 px давала увод 0.9 px при линейном допуске и
 * 0.34 при степенном, узлов лишь на пятую часть больше. Окно угла не
 * масштабируется вовсе: оно про скругление антиалиасинга, а то в пикселе
 * при любом размере; окно, растущее с картинкой, читало круглые концы
 * штрихов как углы — 226 ложных углов на 40 иконок против нуля. «Мусор»
 * растёт линейно с размером (не квадратом): крапина рендера — это несколько
 * пикселей при любом размере, а квадратичный порог на 512 px съедал точки
 * конфетти в десять пикселей.
 */
const SCALED = { simplify: 0.6, fitError: 0.6, minArea: 1 };

export const sizeFactor = (w, h) =>
  Math.max(0.25, Math.min(40, Math.min(w, h) / BASE_SIZE));

/** Круглый шаг: 1, 2 или 5 на порядок — чтобы в поле не лезли хвосты. */
function niceStep(range) {
  if (!(range > 0)) return 0.01;
  const e = 10 ** Math.floor(Math.log10(range));
  const m = range / e;
  return (m < 1.5 ? 1 : m < 3.5 ? 2 : m < 7.5 ? 5 : 10) * e;
}

/** Прижать к шагу и обрезать хвост двоичной дроби: 1.2000000000000002 — не число для поля. */
function snap(v, step) {
  const digits = Math.max(0, Math.min(6, -Math.floor(Math.log10(step))));
  return Number((Math.round(v / step) * step).toFixed(digits));
}

/** Настройка, пересчитанная под размер кропа: и значение, и пределы. */
export function scaleControl(c, f) {
  // Окно угла: не меньше половины умолчания (скругление антиалиасинга) и не
  // больше умолчания — на крошечном кропе окно в четыре пикселя было бы
  // шире самой фигуры, а на большом расти ему незачем.
  if (c.key === 'cornerSpan') {
    const v = Math.min(c.value, Math.max(c.value / 2, (c.value * f) / 2));
    return { ...c, value: snap(v, c.step) };
  }
  const power = SCALED[c.key];
  if (!power || c.type === 'select') return c;
  const k = f ** power;
  const min = c.min * k;
  const max = c.max * k;
  const step = niceStep((max - min) / 80);
  return {
    ...c,
    min: snap(min, step),
    max: snap(max, step),
    step,
    value: Math.max(min, Math.min(max, snap(c.value * k, step))),
  };
}

export const scaleControls = (f) => CONTROLS.map((c) => scaleControl(c, f));

/** Умолчания, подогнанные под размер кропа. */
export const suggest = (w, h) =>
  Object.fromEntries(scaleControls(sizeFactor(w, h)).map((c) => [c.key, c.value]));
